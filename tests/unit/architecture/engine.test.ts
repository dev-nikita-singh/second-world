describe("fingerprints", () => {
  it("are stable when lines shift and differ between distinct findings", async () => {
    const body = `export async function charge() {\n  await fetch("https://pay.io/c");\n}\nexport async function refund() {\n  await fetch("https://pay.io/r");\n}\n`;
    const { result: a } = await inspectFiles({ "src/p.ts": body });
    const { result: b } = await inspectFiles({
      "src/p.ts": `// header\n\n\n/** docs */\n${body.replace("charge() {\n", "charge() {\n  const x = 1;\n\n")}`,
    });
    const fa = byRule(a, "ARCH001").map((f) => f.fingerprint);
    const fb = byRule(b, "ARCH001").map((f) => f.fingerprint);
    expect(fa).toHaveLength(2);
    expect(new Set(fa).size).toBe(2);
    expect(fb).toEqual(fa);
    expect(byRule(a, "ARCH001")[0]?.locations[0]?.line).not.toBe(byRule(b, "ARCH001")[0]?.locations[0]?.line);
  });

  it("identical snippets in the same symbol get distinct ordinals", async () => {
    const { result } = await inspectFiles({
      "src/p.ts": `export async function f() {\n  await fetch("https://a.io");\n  await fetch("https://a.io");\n}`,
    });
    const fps = byRule(result, "ARCH001").map((f) => f.fingerprint);
    expect(new Set(fps).size).toBe(2);
  });
});

describe("graph exports", () => {
  it("toDot / toMermaid / toJSON; graph is non-enumerable on data; impactOf", async () => {
    const { data, result } = await inspectFiles({
      "src/app.ts": `
import express from "express";
import { Pool } from "pg";
const pool = new Pool({ max: 2 });
const app = express();
app.get("/users", async (q, s) => { s.json(await listUsers()); });
async function listUsers() { return pool.query("SELECT \\"x\\" FROM users"); }
`,
    });
    const dot = data.graph.toDot();
    expect(dot).toMatch(/^digraph architecture \{/);
    expect(dot).toContain('"route:GET /users" -> "fn:src/app.ts#GET /users" [label="calls"]');
    expect(dot).toContain('"fn:src/app.ts#listUsers" -> "datastore:postgres" [label="reads"]');
    expect(dot).toContain("shape=cylinder");
    expect(dot).not.toContain("module:");
    expect(data.graph.toDot({ view: "modules" })).toContain('"module:src/app.ts"');
    const mm = data.graph.toMermaid();
    expect(mm.startsWith("flowchart LR\n")).toBe(true);
    expect(mm).toMatch(/n\d+\(\["GET \/users"\]\)/);
    expect(mm).toMatch(/-->\|reads\|/);
    const json = data.graph.toJSON();
    expect(json.nodes.length).toBe(data.components.length);
    expect(Object.keys(JSON.parse(JSON.stringify(result.data)))).not.toContain("graph");
    expect(data.graph.impactOf("datastore:postgres", { kinds: ["route"] })).toEqual(["route:GET /users"]);
    expect(data.reachability["route:GET /users"]).toEqual(["datastore:postgres"]);
    expect(data.impact["datastore:postgres"]).toEqual(["route:GET /users"]);
    expect(data.metrics.deepestChain.path[0]).toBe("route:GET /users");
    expect(data.metrics.deepestChain.length).toBe(3);
  });
});

describe("discovery", () => {
  it("respects .gitignore (nested), .swignore, default ignores, size limit and generated files", async () => {
    const dir = await writeProject({
      ".gitignore": "ignored/\n",
      ".swignore": "legacy/**\n",
      "pkg/.gitignore": "secret.ts\n",
      "src/a.ts": "export const a = 1;",
      "ignored/x.ts": "export const x = 1;",
      "legacy/old.ts": "export const o = 1;",
      "pkg/secret.ts": "export const s = 1;",
      "pkg/ok.ts": "export const ok = 1;",
      "node_modules/m/index.js": "module.exports = 1;",
      "dist/out.js": "x",
      "src/types.d.ts": "export {};",
      "src/gen.ts": "// @generated by protoc. DO NOT EDIT\nexport const g = 1;",
      "src/big.ts": `export const big = "${"x".repeat(2000)}";`,
      "tools/script.py": "print(1)",
    });
    try {
      const d = await discover({
        root: dir.path,
        exclude: [],
        maxFiles: 100,
        maxFileSizeBytes: 1000,
        gitignore: true,
      });
      expect(d.files).toEqual(["pkg/ok.ts", "src/a.ts"]);
      expect(d.skipped.map((s) => s.file).sort()).toEqual(["src/big.ts", "src/gen.ts"]);
      expect(d.limitations.map((l) => l.code)).toEqual(
        expect.arrayContaining(["ARCH_FILES_SKIPPED", "ARCH_UNSUPPORTED_LANGUAGE"]),
      );
      const d2 = await discover({
        root: dir.path,
        exclude: [],
        maxFiles: 1,
        maxFileSizeBytes: 1e6,
        gitignore: false,
      });
      expect(d2.files).toHaveLength(1);
      expect(d2.limitations.some((l) => l.code === "ARCH_MAX_FILES")).toBe(true);
    } finally {
      await dir.cleanup();
    }
  });

  it("tsconfig (JSONC, references) and npm workspaces", async () => {
    const dir = await writeProject({
      "tsconfig.json": `{ // comment\n "compilerOptions": { "strict": true, }, "references": [{ "path": "./packages/lib" }] }`,
      "packages/lib/tsconfig.json": `{ "compilerOptions": {} }`,
      "package.json": JSON.stringify({ name: "root", workspaces: ["packages/*"] }),
      "packages/lib/package.json": JSON.stringify({ name: "@acme/lib", main: "dist/index.js" }),
      "packages/lib/src/index.ts": "export const lib = () => 1;",
      "packages/app/package.json": JSON.stringify({ name: "@acme/app" }),
      "packages/app/src/main.ts": `import { lib } from "@acme/lib";\nexport const run = () => lib();`,
    });
    try {
      const d = await discover({
        root: dir.path,
        exclude: [],
        maxFiles: 100,
        maxFileSizeBytes: 1e6,
        gitignore: true,
      });
      expect(d.tsconfig).toBeDefined();
      expect(d.tsconfigReferences).toHaveLength(1);
      expect(d.workspaces.map((w) => [w.name, w.entry])).toEqual([
        ["@acme/app", undefined],
        ["@acme/lib", "packages/lib/src/index.ts"],
      ]);
      const r = await inspectArchitecture({ project: dir.path, noCache: true });
      expect(r.data?.project.workspaces).toEqual(["@acme/app", "@acme/lib"]);
      expect(
        r.data?.edges.some(
          (e) => e.from === "module:packages/app/src/main.ts" && e.to === "module:packages/lib/src/index.ts",
        ),
      ).toBe(true);
      // Known limitation: without node_modules links the TypeChecker cannot resolve symbols across workspace
      // packages, so only the module edge (workspace heuristic) exists, not the call edge.
      expect(
        r.data?.edges.some(
          (e) => e.from === "fn:packages/app/src/main.ts#run" && e.to === "fn:packages/lib/src/index.ts#lib",
        ),
      ).toBe(false);
      expect(
        r.data?.edges.find((e) => e.to === "module:packages/lib/src/index.ts")?.evidence[0]?.heuristic,
      ).toBe(true);
    } finally {
      await dir.cleanup();
    }
  });
});

describe("safety: never executes project code", () => {
  it("a module that writes a marker when executed is analysed but never run", async () => {
    const dir = await writeProject({
      "src/evil.ts": `
import { writeFileSync } from "node:fs";
writeFileSync(new URL("../EXECUTED.marker", import.meta.url), "x");
export default function handler() { writeFileSync("EXECUTED2.marker", "y"); }
`,
      "src/evil.js": `require("fs").writeFileSync(__dirname + "/../EXECUTED3.marker", "z");`,
      "sw.config.ts": `import { writeFileSync } from "node:fs"; writeFileSync("EXECUTED4.marker", "w"); export default {};`,
      "tsconfig.json": `{ "compilerOptions": { "plugins": [{ "name": "./src/evil.js" }] } }`,
    });
    try {
      const r = await inspectArchitecture({ project: dir.path, noCache: true });
      expect(r.status).not.toBe("error");
      expect(r.data?.project.files).toBe(3);
      for (const m of ["EXECUTED.marker", "EXECUTED2.marker", "EXECUTED3.marker", "EXECUTED4.marker"]) {
        expect(existsSync(dir.join(m))).toBe(false);
        expect(existsSync(path.join(process.cwd(), m))).toBe(false);
      }
    } finally {
      await dir.cleanup();
    }
  });
});

describe("incremental cache", () => {
  it("reuses facts for unchanged files and invalidates dependents of changed files", async () => {
    const dir = await writeProject({
      "src/a.ts": `import { b } from "./b.js";\nexport async function a() { return b(); }`,
      "src/b.ts": `export async function b() { return fetch("https://x.io"); }`,
      "src/c.ts": `export const c = 1;`,
    });
    const cacheDir = dir.join("cache");
    try {
      const r1 = await inspectArchitecture({ project: dir.path, cacheDir });
      expect(r1.data?.metrics.filesFromCache).toBe(0);
      expect(existsSync(cacheDir)).toBe(true);
      const r2 = await inspectArchitecture({ project: dir.path, cacheDir });
      expect(r2.data?.metrics.filesFromCache).toBe(3);
      expect(r2.findings.map((f) => f.fingerprint)).toEqual(r1.findings.map((f) => f.fingerprint));
      // change b → a (imports b) and b are re-extracted, c stays cached
      await writeFile(
        dir.join("src/b.ts"),
        `export async function b() { return fetch("https://x.io", { signal: AbortSignal.timeout(5) }); }`,
      );
      const r3 = await inspectArchitecture({ project: dir.path, cacheDir });
      expect(r3.data?.metrics.filesFromCache).toBe(1);
      expect(byRule(r3, "ARCH001")).toHaveLength(0);
      // noCache ignores the cache entirely
      const r4 = await inspectArchitecture({ project: dir.path, cacheDir, noCache: true });
      expect(r4.data?.metrics.filesFromCache).toBe(0);
      const raw = JSON.parse(
        await readFile(
          path.join(cacheDir, (await import("node:fs")).readdirSync(cacheDir)[0] as string),
          "utf8",
        ),
      );
      expect(Object.keys(raw.files).sort()).toEqual(["src/a.ts", "src/b.ts", "src/c.ts"]);
    } finally {
      await dir.cleanup();
    }
  });
});

describe("engine contract", () => {
  it("schema defaults, invalid input → ConfigError, engine object, limitations always present", async () => {
    const parsed = ArchitectureInputSchema.parse({});
    expect(parsed).toMatchObject({
      project: ".",
      maxFiles: 20000,
      frameworks: "auto",
      noCache: false,
      rules: {},
    });
    expect(() => parseArchitectureInput({ maxFiles: -1 })).toThrow(ConfigError);
    expect(() => parseArchitectureInput({ rules: { ARCH001: "loud" } })).toThrow(/rules/);
    expect(parseArchitectureInput({ rules: { ARCH001: ["warn", { a: 1 }] } }).rules.ARCH001).toEqual([
      "warn",
      { a: 1 },
    ]);
    expect(architectureEngine.id).toBe("architecture");
    expect(architectureEngine.requires).toEqual([{ cap: "fs.read" }]);
    const dir = await makeTmpDir("sw-arch-empty-");
    try {
      const ctx = createEngineContext();
      const r = await architectureEngine.run(
        parseArchitectureInput({ project: dir.path, noCache: true }),
        ctx,
      );
      expect(r.engine).toBe("architecture");
      // Nothing to inspect is "nothing measured" (exit 5), not a pass.
      expect(r.status).toBe("error");
      expect(r.limitations.map((l) => l.code)).toEqual(
        expect.arrayContaining(["ARCH_STATIC_ONLY", "ARCH_NO_FILES"]),
      );
      expect(ctx.evidence.results).toBeDefined();
    } finally {
      await dir.cleanup();
    }
  });

  it("cancelled signal → status cancelled", async () => {
    const ac = new AbortController();
    ac.abort();
    const dir = await writeProject({ "a.ts": "export const a = 1;" });
    try {
      const r = await inspectArchitecture({ project: dir.path, noCache: true }, { signal: ac.signal });
      expect(r.status).toBe("cancelled");
    } finally {
      await dir.cleanup();
    }
  });

  it("plugin rule via defineTsRule (ESLint-like visitors)", async () => {
    const r = defineTsRule({
      meta: ruleMeta("acme/no-eval", "No eval", "high", "security", "error", "Do not use eval"),
      create: (api) => ({
        CallExpression(node) {
          const c = node as import("typescript").CallExpression;
          if (api.ts?.isIdentifier(c.expression) && c.expression.text === "eval")
            api.report({ node, message: "eval() call" });
        },
      }),
    });
    const { result } = await inspectFiles(
      { "src/e.ts": `export const f = (s: string) => eval(s);\n// sw-ignore acme/no-eval ok\neval("1");` },
      {},
      { extractors: [r.extractor], rules: [r.rule] },
    );
    const f = byRule(result, "acme/no-eval");
    expect(f).toHaveLength(1);
    expect(f[0]?.locations[0]?.line).toBe(1);
  });
});

describe("helpers", () => {
  it("glob matcher", () => {
    expect(globToRegExp("src/**/*.ts").test("src/a/b/c.ts")).toBe(true);
    expect(globToRegExp("src/**/*.ts").test("src/c.ts")).toBe(true);
    expect(globToRegExp("src/*.{ts,js}").test("src/x.js")).toBe(true);
    expect(globToRegExp("src/*.ts").test("src/a/x.ts")).toBe(false);
  });
  it("suppression parsing", () => {
    const s = parseSuppressions(
      `a();\n// sw-ignore ARCH001, arch005 because\n\nb(); /* sw-ignore ARCH002 inline */\n`,
    );
    expect(s).toEqual([
      { line: 4, rules: ["ARCH001", "ARCH005"], reason: "because" },
      { line: 4, rules: ["ARCH002"], reason: "inline" },
    ]);
    expect(findSuppression(s, "ARCH005", 4)?.reason).toBe("because");
    expect(findSuppression(s, "ARCH003", 4)).toBeUndefined();
  });
});
